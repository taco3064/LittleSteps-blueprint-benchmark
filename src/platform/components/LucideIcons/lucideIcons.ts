/**
 * Explicit registry of the lucide icons referenced by name (as strings) in
 * static data. Importing only these lets the bundler tree-shake the rest of
 * lucide-react instead of pulling the whole library via `import * as Icons`.
 * Unknown names fall back to `HelpCircle` so a stale data string degrades
 * gracefully rather than rendering `undefined` (which crashes React).
 */
